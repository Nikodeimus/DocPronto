const PROFILE_DESCRIPTION = "DOCPronto RGB";
const D50 = [0.9642, 1, 0.8249];
const MAX_PDFA_PAGES = 100;
const MAX_PDFA_PAGE_PIXELS = 40_000_000;
const MAX_PDFA_TOTAL_PIXELS = 120_000_000;

function align4(value) {
  return (value + 3) & ~3;
}

function writeAscii(target, offset, value) {
  for (let index = 0; index < value.length; index += 1) target[offset + index] = value.charCodeAt(index);
}

function writeUint16(view, offset, value) {
  view.setUint16(offset, value, false);
}

function writeUint32(view, offset, value) {
  view.setUint32(offset, value >>> 0, false);
}

function writeFixed(view, offset, value) {
  view.setInt32(offset, Math.round(value * 65536), false);
}

function xyzTag(values) {
  const bytes = new Uint8Array(20);
  const view = new DataView(bytes.buffer);
  writeAscii(bytes, 0, "XYZ ");
  values.forEach((value, index) => writeFixed(view, 8 + index * 4, value));
  return bytes;
}

function srgbCurveTag() {
  const sampleCount = 256;
  const bytes = new Uint8Array(align4(12 + sampleCount * 2));
  const view = new DataView(bytes.buffer);
  writeAscii(bytes, 0, "curv");
  writeUint32(view, 8, sampleCount);
  for (let index = 0; index < sampleCount; index += 1) {
    const encoded = index / (sampleCount - 1);
    const linear = encoded <= 0.04045
      ? encoded / 12.92
      : ((encoded + 0.055) / 1.055) ** 2.4;
    writeUint16(view, 12 + index * 2, Math.round(linear * 65535));
  }
  return bytes;
}

function textTag(value) {
  const text = new TextEncoder().encode(`${value}\0`);
  const bytes = new Uint8Array(align4(8 + text.length));
  writeAscii(bytes, 0, "text");
  bytes.set(text, 8);
  return bytes;
}

function descriptionTag(value) {
  const ascii = new TextEncoder().encode(`${value}\0`);
  const bytes = new Uint8Array(align4(90 + ascii.length));
  const view = new DataView(bytes.buffer);
  writeAscii(bytes, 0, "desc");
  writeUint32(view, 8, ascii.length);
  bytes.set(ascii, 12);
  const unicodeOffset = 12 + ascii.length;
  writeUint32(view, unicodeOffset, 0);
  writeUint32(view, unicodeOffset + 4, 0);
  writeUint16(view, unicodeOffset + 8, 0);
  bytes[unicodeOffset + 10] = 0;
  return bytes;
}

export function createDocProntoRgbProfile() {
  const tags = [
    ["desc", descriptionTag(PROFILE_DESCRIPTION)],
    ["cprt", textTag("Generated by DOCPronto")],
    ["wtpt", xyzTag(D50)],
    ["rXYZ", xyzTag([0.4360747, 0.2225045, 0.0139322])],
    ["gXYZ", xyzTag([0.3850649, 0.7168786, 0.0971045])],
    ["bXYZ", xyzTag([0.1430804, 0.0606169, 0.7141733])],
    ["rTRC", srgbCurveTag()],
    ["gTRC", srgbCurveTag()],
    ["bTRC", srgbCurveTag()],
  ];
  const tagTableSize = 4 + tags.length * 12;
  let nextOffset = align4(128 + tagTableSize);
  const entries = tags.map(([signature, data]) => {
    const entry = { signature, data, offset: nextOffset };
    nextOffset += align4(data.length);
    return entry;
  });
  const profile = new Uint8Array(nextOffset);
  const view = new DataView(profile.buffer);

  writeUint32(view, 0, profile.length);
  writeUint32(view, 8, 0x02100000);
  writeAscii(profile, 12, "mntr");
  writeAscii(profile, 16, "RGB ");
  writeAscii(profile, 20, "XYZ ");
  [2026, 1, 1, 0, 0, 0].forEach((value, index) => writeUint16(view, 24 + index * 2, value));
  writeAscii(profile, 36, "acsp");
  writeAscii(profile, 40, "MSFT");
  writeAscii(profile, 48, "DOCP");
  writeUint32(view, 64, 0);
  D50.forEach((value, index) => writeFixed(view, 68 + index * 4, value));
  writeAscii(profile, 80, "DOCP");
  writeUint32(view, 128, entries.length);

  entries.forEach((entry, index) => {
    const tableOffset = 132 + index * 12;
    writeAscii(profile, tableOffset, entry.signature);
    writeUint32(view, tableOffset + 4, entry.offset);
    writeUint32(view, tableOffset + 8, entry.data.length);
    profile.set(entry.data, entry.offset);
  });
  return profile;
}

function pdfaLimitError(code, message) {
  return Object.assign(new Error(message), { code });
}

export function assertPdfARasterBudget({ pageCount, pagePixels, totalPixels }) {
  if (!Number.isInteger(pageCount) || pageCount < 1 || pageCount > MAX_PDFA_PAGES) {
    throw pdfaLimitError("PDFA_PAGE_LIMIT", `O PDF/A aceita até ${MAX_PDFA_PAGES} páginas por operação.`);
  }
  if (!Number.isFinite(pagePixels) || pagePixels < 0 || pagePixels > MAX_PDFA_PAGE_PIXELS) {
    throw pdfaLimitError(
      "PDFA_PAGE_TOO_LARGE",
      "Uma página excede o limite seguro de resolução. Escolha um DPI menor.",
    );
  }
  if (!Number.isFinite(totalPixels) || totalPixels < 0 || totalPixels > MAX_PDFA_TOTAL_PIXELS) {
    throw pdfaLimitError(
      "PDFA_MEMORY_LIMIT",
      "O documento excede o limite seguro de memória. Escolha um DPI menor ou divida o PDF.",
    );
  }
}

function xmlEscape(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&apos;",
  })[character]);
}

function xmpPacket({ title, createdAt }) {
  const isoDate = createdAt.toISOString();
  return `<?xpacket begin="\uFEFF" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="DOCPronto">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
   xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/"
   xmlns:pdf="http://ns.adobe.com/pdf/1.3/"
   xmlns:xmp="http://ns.adobe.com/xap/1.0/"
   xmlns:dc="http://purl.org/dc/elements/1.1/"
   pdfaid:part="2" pdfaid:conformance="B"
   pdf:Producer="DOCPronto"
   xmp:CreatorTool="DOCPronto"
   xmp:CreateDate="${isoDate}"
   xmp:ModifyDate="${isoDate}">
   <dc:format>application/pdf</dc:format>
   <dc:title><rdf:Alt><rdf:li xml:lang="x-default">${xmlEscape(title)}</rdf:li></rdf:Alt></dc:title>
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>
<?xpacket end="w"?>`;
}

function createFileIdentifier() {
  const bytes = new Uint8Array(16);
  if (globalThis.crypto?.getRandomValues) {
    globalThis.crypto.getRandomValues(bytes);
  } else {
    let state = (Date.now() ^ Math.floor(Math.random() * 0xFFFFFFFF)) >>> 0;
    for (let index = 0; index < bytes.length; index += 1) {
      state ^= state << 13;
      state ^= state >>> 17;
      state ^= state << 5;
      bytes[index] = state & 0xFF;
    }
  }
  return [...bytes].map(value => value.toString(16).padStart(2, "0")).join("").toUpperCase();
}

export function markDocumentAsPdfA2b(document, PDFLib, options = {}) {
  const title = String(options.title || "Documento arquivado");
  const createdAt = options.createdAt instanceof Date ? options.createdAt : new Date();
  const { PDFHexString, PDFName, PDFString } = PDFLib;
  const { context, catalog } = document;

  document.setTitle(title);
  document.setCreator("DOCPronto");
  document.setProducer("DOCPronto");
  document.setCreationDate(createdAt);
  document.setModificationDate(createdAt);
  const fileIdentifier = createFileIdentifier();
  context.trailerInfo.ID = context.obj([
    PDFHexString.of(fileIdentifier),
    PDFHexString.of(fileIdentifier),
  ]);

  const profileStream = context.flateStream(createDocProntoRgbProfile(), {
    N: 3,
    Alternate: PDFName.of("DeviceRGB"),
  });
  const profileReference = context.register(profileStream);
  const outputIntent = context.obj({
    Type: "OutputIntent",
    S: "GTS_PDFA1",
    OutputConditionIdentifier: PDFString.of(PROFILE_DESCRIPTION),
    Info: PDFString.of(`${PROFILE_DESCRIPTION} color profile`),
    RegistryName: PDFString.of("https://www.color.org"),
    DestOutputProfile: profileReference,
  });
  const outputIntentReference = context.register(outputIntent);
  catalog.set(PDFName.of("OutputIntents"), context.obj([outputIntentReference]));

  const metadataStream = context.stream(new TextEncoder().encode(xmpPacket({ title, createdAt })), {
    Type: PDFName.of("Metadata"),
    Subtype: PDFName.of("XML"),
  });
  catalog.set(PDFName.of("Metadata"), context.register(metadataStream));
  return document;
}

function invalidPdfA(message) {
  return Object.assign(new Error(message), { code: "INVALID_PDFA" });
}

function decodedStream(PDFLib, stream) {
  try {
    return PDFLib.decodePDFRawStream(stream).decode();
  } catch {
    return stream?.getContents?.() || stream?.contents;
  }
}

export async function validatePdfA2b(bytes, PDFLib, options = {}) {
  let document;
  try {
    document = await PDFLib.PDFDocument.load(bytes, {
      ignoreEncryption: false,
      throwOnInvalidObject: true,
      updateMetadata: false,
    });
  } catch (error) {
    throw invalidPdfA(`O PDF/A gerado não pôde ser reaberto: ${error.message}`);
  }
  const { PDFArray, PDFDict, PDFName, PDFRawStream } = PDFLib;
  const metadata = document.catalog.lookupMaybe(PDFName.of("Metadata"), PDFRawStream);
  if (!metadata) throw invalidPdfA("O PDF/A gerado não contém os metadados XMP obrigatórios.");
  const xmp = new TextDecoder().decode(decodedStream(PDFLib, metadata));
  if (!/pdfaid:part="2"/.test(xmp) || !/pdfaid:conformance="B"/.test(xmp)) {
    throw invalidPdfA("Os metadados XMP não identificam corretamente o padrão PDF/A-2b.");
  }
  const serialized = new TextDecoder("windows-1252").decode(bytes);
  const identifierMatch = serialized.match(/\/ID\s*\[\s*<([A-Fa-f0-9]{32})>\s*<[A-Fa-f0-9]{32}>\s*\]/);
  if (!identifierMatch) throw invalidPdfA("O identificador permanente do arquivo PDF/A está ausente.");

  const intents = document.catalog.lookupMaybe(PDFName.of("OutputIntents"), PDFArray);
  if (!intents || intents.size() !== 1) throw invalidPdfA("O PDF/A precisa conter exatamente um perfil de cor de saída.");
  const intent = document.context.lookup(intents.get(0), PDFDict);
  const profile = document.context.lookup(intent?.get(PDFName.of("DestOutputProfile")), PDFRawStream);
  const profileBytes = profile && decodedStream(PDFLib, profile);
  const profileSignature = profileBytes
    ? String.fromCharCode(...profileBytes.subarray(36, 40))
    : "";
  if (!profileBytes || profileBytes.length < 132 || profileSignature !== "acsp") {
    throw invalidPdfA("O perfil de cor ICC do PDF/A está ausente ou inválido.");
  }

  const pageCount = document.getPageCount();
  if (options.expectedPageCount != null && pageCount !== options.expectedPageCount) {
    throw invalidPdfA(`O PDF/A deveria ter ${options.expectedPageCount} páginas, mas possui ${pageCount}.`);
  }
  const outputCondition = intent.get(PDFName.of("OutputConditionIdentifier"))?.decodeText?.() || "";
  return {
    valid: true,
    part: "2",
    conformance: "B",
    pageCount,
    outputCondition,
    fileIdentifier: identifierMatch[1].toUpperCase(),
  };
}
